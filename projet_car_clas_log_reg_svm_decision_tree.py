def predict_ui(marque, transmission, quartier, annee, prix):

    if not marque or not transmission or not quartier:

        # On renvoie aussi l'état courant du dashboard (inchangé)
        return (
            "⚠️ Veuillez sélectionner toutes les options.",
            "",
            _build_kpi_html(prediction_history),
            _build_dashboard_table(prediction_history),
        )

    try:

        prediction, confidence = predict_single(
            marque, transmission, quartier, annee, prix
        )

    except ValueError as e:

        return (
            f"❌ Erreur : {e}",
            "",
            _build_kpi_html(prediction_history),
            _build_dashboard_table(prediction_history),
        )

    # Mise à jour de l'historique du dashboard
    _add_to_history(marque, annee, prix, quartier, prediction, confidence)

    return (
        prediction,
        f"{confidence * 100:.1f}%",
        _build_kpi_html(prediction_history),
        _build_dashboard_table(prediction_history),
    )


