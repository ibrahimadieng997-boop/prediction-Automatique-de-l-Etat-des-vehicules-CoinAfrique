def predict_single(marque, transmission, quartier, annee, prix):

    try:
        marque_enc = encoders[0].transform([marque])[0]
        trans_enc = encoders[1].transform([transmission])[0]
        quartier_enc = encoders[2].transform([quartier])[0]

    except ValueError as e:

        raise ValueError(
            f"Valeur catégorielle inconnue du modèle : {e}"
        )

    # IMPORTANT : cet ordre doit correspondre exactement à l'ordre des
    # colonnes utilisé lors de l'entraînement du scaler/modèle, à savoir
    # [Marque, Année, Transmission, Prix, Quartier]. L'ancien ordre
    # [Marque, Transmission, Quartier, Année, Prix] ne correspondait pas
    # à l'entraînement et faisait retomber le modèle sur "D'occasion"
    # presque à chaque prédiction.
    x_new = np.array([
        marque_enc,
        float(annee),
        trans_enc,
        float(prix),
        quartier_enc,
    ]).reshape(1, -1)

    x_scaled = scaler.transform(x_new)

    y_pred = rf.predict(x_scaled)[0]

    probas = rf.predict_proba(x_scaled)[0]

    confidence = float(np.max(probas))

    return str(clasnames[y_pred]), confidence


